"""Write datasets/<domain>/README.md from the snapshot's manifest (called by scripts/snapshot.sh)."""
import json
import sys

name, out = sys.argv[1], sys.argv[2]
m = json.load(open(f"{out}/manifest.json", encoding="utf-8"))
tables = m.get("row_counts") or {}
total = sum(tables.values())
text = f"""# {name} — published dataset snapshot

Generated by `scripts/snapshot.sh {name}`; do not edit by hand. Pack `{name}` v{m.get('domain_version', '?')},
dsgen v{m.get('framework_version', '?')}.

| | |
|---|---|
| "Today" in the data (as-of) | **{m['as_of']}** — freeze the application clock to this date, or regenerate |
| Seed / scale | {m['seed']} / {m.get('scale', 1.0)} |
| Tables / rows | {len(tables)} / {total:,} |
| Verification | `verification.json`; `FACTS.md` lists the numbers to present from |

Contents: `csv/` (one file per table, DDL column order, empty = NULL), `sql/` (DDL per dialect, loaders, the read-only
AI account, the model-facing schema text, PII tags), `documents/` (customer messages, photo, provenance), `FACTS.md`,
`REVIEW.md`, `manifest.json`, `verification.json`, and `summary.html` (a one-page overview for colleagues).

Loading: `sql/load-h2.sql` reads the CSVs from `./{out}/csv` relative to the repository root (start H2 there), or use
`sql/load-h2-classpath.sql` after copying `csv/` onto the application's classpath; `sql/load-postgres.sql` is for psql.
A ready-to-use H2 file is not committed (binary, tens of MB); build it in seconds:

```bash
python3 -m dsgen {name} generate --out {out} --csv-path-prefix ./{out}/csv --h2-file
```

Reproducibility: the same pack version, seed, as-of and scale give byte-identical CSVs (SHA-256 per table in
`manifest.json`); `scripts/test.sh` fails when this snapshot no longer matches what the pack generates.
"""
open(f"{out}/README.md", "w", encoding="utf-8").write(text)
print(f"wrote {out}/README.md")
