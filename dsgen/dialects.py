"""SQL dialects for the generated DDL, loaders and read-only account. Only what differs lives here."""
from __future__ import annotations


class Dialect:
    name = "h2"
    label = "H2 2.x"
    text_type = "CLOB"

    def ddl_header(self, company, version):
        return [f"-- {company} demo schema (generated by dsgen v{version}) — dialect: {self.label}",
                "-- Column order matches the CSV files, so loaders can insert without a column list.", ""]

    def loader(self, spec, csv_prefix):
        lines = ["-- Load the CSV files into H2 with CSVREAD. Run after schema-h2.sql.",
                 f"-- CSV directory: {csv_prefix} (regenerate with --csv-path-prefix to point elsewhere).",
                 "-- Empty CSV fields become NULL. Column order in the CSVs matches the CREATE TABLE statements."]
        for t in spec.tables:
            lines.append(f"INSERT INTO {t} SELECT * FROM CSVREAD('{csv_prefix.rstrip('/')}/{t}.csv', NULL, 'charset=UTF-8');")
        return "\n".join(lines) + "\n"

    def classpath_loader(self, spec):
        lines = ["-- Same loader for a Spring Boot app: copy out/csv/* to src/main/resources/data/ and run this as",
                 "-- spring.sql.init.data-locations=classpath:load-h2-classpath.sql (H2 resolves classpath: URLs)."]
        for t in spec.tables:
            lines.append(f"INSERT INTO {t} SELECT * FROM CSVREAD('classpath:/data/{t}.csv', NULL, 'charset=UTF-8');")
        return "\n".join(lines) + "\n"

    def readonly_user(self, spec, views):
        lines = ["-- Read-only account for the AI's DatabaseProvider (H2 syntax).",
                 "-- It can SELECT the exposed tables and views and nothing else: no hidden tables, no runtime tables, no writes.",
                 "CREATE USER IF NOT EXISTS ai_reader PASSWORD 'ai_reader';"]
        for t in spec.exposed_tables + views:
            lines.append(f"GRANT SELECT ON {t} TO ai_reader;")
        return "\n".join(lines) + "\n"

    def column_comment(self, table, col, text):
        return f"COMMENT ON COLUMN {table}.{col} IS '{text.replace(chr(39), chr(39) * 2)}';"


class Postgres(Dialect):
    name = "postgres"
    label = "PostgreSQL"
    text_type = "TEXT"

    def loader(self, spec, csv_prefix):
        lines = ["-- Load the CSV files into PostgreSQL with psql's client-side \\copy. Run after schema-postgres.sql:",
                 "--   psql -h host -U user -d db -f load-postgres.sql",
                 f"-- CSV directory (on the machine running psql): {csv_prefix}. Empty fields become NULL.",
                 "-- For server-side COPY (file on the database host / a mounted volume) replace \\copy with COPY."]
        for t in spec.tables:
            lines.append(f"\\copy {t} FROM '{csv_prefix.rstrip('/')}/{t}.csv' WITH (FORMAT csv, HEADER true)")
        return "\n".join(lines) + "\n"

    def classpath_loader(self, spec):
        return ""   # no classpath equivalent; use the app's own loader (see integration guide)

    def readonly_user(self, spec, views):
        lines = ["-- Read-only role for the AI's DatabaseProvider (PostgreSQL syntax).",
                 "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ai_reader') THEN",
                 "  CREATE ROLE ai_reader LOGIN PASSWORD 'ai_reader'; END IF; END $$;",
                 "GRANT USAGE ON SCHEMA public TO ai_reader;"]
        for t in spec.exposed_tables + views:
            lines.append(f"GRANT SELECT ON {t} TO ai_reader;")
        return "\n".join(lines) + "\n"


DIALECTS = {"h2": Dialect(), "postgres": Postgres()}

def get(name: str) -> Dialect:
    return DIALECTS[name]
