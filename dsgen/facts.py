"""Render out/FACTS.md from manifest.json + verification.json: generic header, time anchors, row
counts, then the domain's own sections (lifecycle.facts_sections)."""
from __future__ import annotations

import json
import os

from . import VERSION


def render_facts(domain, out: str) -> str:
    m = json.load(open(os.path.join(out, "manifest.json"), encoding="utf-8"))
    v = json.load(open(os.path.join(out, "verification.json"), encoding="utf-8"))
    L = [f"# Facts about this generation — {domain.spec.company}\n",
         f"Generated by dsgen v{m.get('framework_version', VERSION)}, domain `{domain.name}` v{m.get('domain_version', '?')} · as-of **{m['as_of']}** · "
         f"seed {m['seed']} · scale {m['scale']} · Python {m.get('python_version', '?')} · "
         f"{sum(v['checks'][k]['ok'] for k in v['checks'])}/{len(v['checks'])} checks passed.\n",
         "This file is rendered automatically. Do not edit; regenerate.\n",
         "## Time anchors\n", "| | |\n|---|---|",
         f"| Today (as-of) | {m['as_of']} |", f"| History starts | {m['history_start']} |",
         f"| Last month | {m['last_month']} |", f"| First of next month | {m['first_of_next_month']} |"]
    for k, val in m.get("domain_anchors", {}).items():
        L.append(f"| {k.replace('_', ' ')} | {val if not isinstance(val, list) else ' to '.join(map(str, val))} |")
    L.append("\n## Row counts\n\n| Table | Rows |\n|---|---:|")
    for t, n in m["row_counts"].items():
        L.append(f"| {t} | {n:,} |")
    L.append(f"| **total** | **{sum(m['row_counts'].values()):,}** |\n")
    rq, le, lu = m.get("review_queue"), m.get("llm_estimate"), m.get("llm_usage")
    if rq:
        L.append("## Review and cost\n")
        L.append(f"Review queue: {rq['items']} items, {rq['demo_critical']} demo-critical, {rq['approved']} approved (see REVIEW.md).")
        if lu:
            L.append(f"\nLLM/image calls in this run: {lu['calls']} ({lu['images']} images, providers {', '.join(lu['providers']) or 'none'}), cost ${lu['cost_usd']:.2f}.")
        if le:
            cheapest = next(iter(le["cost_by_mode_usd"].items()))
            L.append(f"\nIf an LLM wrote every text item ({le['text_items']:,} items, ~{le['text_output_tokens']:,} tokens): "
                     + ", ".join(f"{k.split(' ')[0]} ${v['llm_writes_every_item']:.2f}" for k, v in le["cost_by_mode_usd"].items() if "batch" not in k)
                     + " (see ESTIMATE.md).\n")
    sections = domain.hook("facts_sections")
    if sections:
        L.append(sections(m, v))
    text = "\n".join(L).rstrip() + "\n"
    with open(os.path.join(out, "FACTS.md"), "w", encoding="utf-8") as f:
        f.write(text)
    return text
